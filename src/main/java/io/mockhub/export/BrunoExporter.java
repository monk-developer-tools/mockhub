package io.mockhub.export;

import com.github.tomakehurst.wiremock.stubbing.StubMapping;
import io.mockhub.project.Project;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

public final class BrunoExporter implements CollectionExporter {
  @Override
  public String format() {
    return "bruno";
  }

  @Override
  public String contentType() {
    return "application/zip";
  }

  @Override
  public String fileName(Project project) {
    return project.slug() + "-bruno.zip";
  }

  @Override
  public byte[] export(Project project, List<StubMapping> stubs, String mockUrl) throws IOException {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    String root = project.slug() + "/";
    try (ZipOutputStream zip = new ZipOutputStream(bytes)) {
      put(zip, root + "bruno.json", """
          {
            "version": "1",
            "name": "%s",
            "type": "collection",
            "ignore": ["node_modules", ".git"]
          }
          """.formatted(project.name().replace("\"", "'") + " (MockHub)"));
      put(zip, root + "collection.bru", "docs {\n" + indent(
          "Generated by MockHub for project **" + project.name() + "**.\n\n"
              + "Select the `MockHub` environment. Change `baseUrl` to call the real service.", 2) + "\n}\n");
      put(zip, root + "environments/MockHub.bru",
          "vars {\n  baseUrl: " + mockUrl + "\n}\n");

      Set<String> folders = new HashSet<>();
      Map<String, Integer> seqByFolder = new HashMap<>();
      Set<String> usedNames = new HashSet<>();
      for (SampleRequest r : SampleRequest.fromStubs(project, stubs)) {
        String folder = safeName(r.folder());
        if (folders.add(folder)) {
          put(zip, root + folder + "/folder.bru", "meta {\n  name: " + r.folder() + "\n}\n");
        }
        int seq = seqByFolder.merge(folder, 1, Integer::sum);
        String file = uniqueName(root + folder + "/" + safeName(r.name()), usedNames) + ".bru";
        put(zip, file, bru(r, seq));
      }
    }
    return bytes.toByteArray();
  }

  static String bru(SampleRequest r, int seq) {
    StringBuilder b = new StringBuilder();
    b.append("meta {\n  name: ").append(r.name().replace("\n", " ")).append("\n  type: http\n  seq: ").append(seq).append("\n}\n\n");

    String method = r.method().toLowerCase(Locale.ROOT);
    if (!Set.of("get", "post", "put", "patch", "delete", "options", "head").contains(method)) method = "get";
    StringBuilder url = new StringBuilder("{{baseUrl}}").append(r.path().equals("/") ? "" : r.path());
    if (!r.query().isEmpty()) {
      url.append('?');
      r.query().forEach((k, v) -> url.append(k).append('=').append(v).append('&'));
      url.setLength(url.length() - 1);
    }
    boolean hasBody = r.body() != null && !"none".equals(r.bodyType());
    b.append(method).append(" {\n  url: ").append(url)
        .append("\n  body: ").append(hasBody ? r.bodyType() : "none")
        .append("\n  auth: none\n}\n\n");

    if (!r.query().isEmpty()) b.append(block("params:query", r.query()));
    if (!r.pathVariables().isEmpty()) b.append(block("params:path", r.pathVariables()));
    if (!r.headers().isEmpty()) b.append(block("headers", r.headers()));
    if (hasBody) {
      b.append("body:").append(r.bodyType()).append(" {\n").append(indent(r.body(), 2)).append("\n}\n\n");
    }
    if (r.expectedStatus() != null) {
      b.append("assert {\n  res.status: eq ").append(r.expectedStatus()).append("\n}\n\n");
    }
    if (!r.description().isEmpty()) {
      b.append("docs {\n").append(indent(r.description(), 2)).append("\n}\n");
    }
    return b.toString();
  }

  private static String block(String name, Map<String, String> values) {
    StringBuilder b = new StringBuilder(name).append(" {\n");
    values.forEach((k, v) -> b.append("  ").append(k).append(": ").append(v.replace("\n", " ")).append('\n'));
    return b.append("}\n\n").toString();
  }

  private static String indent(String text, int spaces) {
    String pad = " ".repeat(spaces);
    return pad + text.replace("\r\n", "\n").replace("\n", "\n" + pad);
  }

  static String safeName(String name) {
    String s = name.replaceAll("[\\\\/:*?\"<>|{}]+", "-").replaceAll("\\s+", " ").trim();
    if (s.length() > 80) s = s.substring(0, 80).trim();
    return s.isEmpty() ? "request" : s;
  }

  private static String uniqueName(String base, Set<String> used) {
    String name = base;
    for (int i = 2; !used.add(name.toLowerCase(Locale.ROOT)); i++) name = base + " " + i;
    return name;
  }

  private static void put(ZipOutputStream zip, String name, String content) throws IOException {
    zip.putNextEntry(new ZipEntry(name));
    zip.write(content.getBytes(StandardCharsets.UTF_8));
    zip.closeEntry();
  }
}
