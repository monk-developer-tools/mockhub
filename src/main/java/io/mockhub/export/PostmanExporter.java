package io.mockhub.export;

import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.github.tomakehurst.wiremock.stubbing.StubMapping;
import io.mockhub.api.Jsons;
import io.mockhub.project.Project;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

public final class PostmanExporter implements CollectionExporter {
  @Override
  public String format() {
    return "postman";
  }

  @Override
  public String contentType() {
    return "application/json";
  }

  @Override
  public String fileName(Project project) {
    return project.slug() + ".postman_collection.json";
  }

  @Override
  public byte[] export(Project project, List<StubMapping> stubs, String mockUrl) throws Exception {
    ObjectNode root = Jsons.object();
    ObjectNode info = root.putObject("info");
    info.put("_postman_id", UUID.nameUUIDFromBytes(project.id().getBytes()).toString());
    info.put("name", project.name() + " (MockHub)");
    info.put("description", (project.description().isBlank() ? "" : project.description() + "\n\n")
        + "Generated by MockHub. `baseUrl` points at the mock; change it to call the real service.");
    info.put("schema", "https://schema.getpostman.com/json/collection/v2.1.0/collection.json");

    ArrayNode vars = root.putArray("variable");
    vars.addObject().put("key", "baseUrl").put("value", mockUrl).put("type", "string");
    if (project.apiKey() != null && project.apiKey().isHidden()) {
      vars.addObject().put("key", "apiKey").put("value", "").put("type", "secret")
          .put("description", "Ask an admin for this project's API key");
    }

    Map<String, ArrayNode> folders = new LinkedHashMap<>();
    ArrayNode items = root.putArray("item");
    for (SampleRequest r : SampleRequest.fromStubs(project, stubs)) {
      ArrayNode folder = folders.computeIfAbsent(r.folder(), name -> {
        ObjectNode f = items.addObject();
        f.put("name", name);
        return f.putArray("item");
      });
      folder.add(item(r));
    }
    return Jsons.MAPPER.writeValueAsBytes(root);
  }

  private static ObjectNode item(SampleRequest r) {
    ObjectNode item = Jsons.object();
    item.put("name", r.name());
    ObjectNode request = item.putObject("request");
    request.put("method", r.method());
    if (!r.description().isEmpty()) request.put("description", r.description());

    ArrayNode headers = request.putArray("header");
    r.headers().forEach((k, v) -> headers.addObject().put("key", k).put("value", v).put("type", "text"));

    ObjectNode url = request.putObject("url");
    StringBuilder raw = new StringBuilder("{{baseUrl}}").append(r.path().equals("/") ? "" : r.path());
    if (!r.query().isEmpty()) {
      raw.append('?');
      r.query().forEach((k, v) -> raw.append(k).append('=').append(v).append('&'));
      raw.setLength(raw.length() - 1);
    }
    url.put("raw", raw.toString());
    url.putArray("host").add("{{baseUrl}}");
    ArrayNode path = url.putArray("path");
    for (String seg : r.path().split("/")) {
      if (!seg.isEmpty()) path.add(seg);
    }
    if (!r.query().isEmpty()) {
      ArrayNode q = url.putArray("query");
      r.query().forEach((k, v) -> q.addObject().put("key", k).put("value", v));
    }
    if (!r.pathVariables().isEmpty()) {
      ArrayNode v = url.putArray("variable");
      r.pathVariables().forEach((k, val) -> v.addObject().put("key", k).put("value", val));
    }

    if (r.body() != null && !"none".equals(r.bodyType())) {
      ObjectNode body = request.putObject("body");
      body.put("mode", "raw");
      body.put("raw", r.body());
      body.putObject("options").putObject("raw").put("language", r.bodyType());
    }

    if (r.expectedStatus() != null) {
      ObjectNode event = item.putArray("event").addObject();
      event.put("listen", "test");
      ObjectNode script = event.putObject("script");
      script.put("type", "text/javascript");
      script.putArray("exec")
          .add("pm.test(\"Status is " + r.expectedStatus() + "\", function () {")
          .add("    pm.response.to.have.status(" + r.expectedStatus() + ");")
          .add("});");
    }
    item.putArray("response");
    return item;
  }
}
